package ru.efir.core.input

/**
 * Платформенные помощники для настройки службы доступности (инъекция ввода).
 *
 * На Android позволяет узнать, включена ли служба Efir в «Специальных
 * возможностях», и открыть соответствующий системный экран настроек.
 * На Desktop обе функции — no-op (ввод на этой стороне не выполняется).
 */

/** Включена ли сейчас служба доступности Efir (Android) / всегда `false` (Desktop). */
expect fun isAccessibilityServiceEnabled(): Boolean

/**
 * Открывает системный экран настроек «Специальные возможности», чтобы
 * пользователь мог включить службу Efir. Возвращает `false`, если открыть
 * не удалось (например, на Desktop).
 */
expect fun openAccessibilitySettings(): Boolean
